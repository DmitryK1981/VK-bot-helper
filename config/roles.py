"""Режимы общения: у каждого — отдельный system prompt."""
from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True, slots=True)
class Role:
    id: str
    emoji: str
    title: str
    description: str
    system_prompt: str

    @property
    def label(self) -> str:
        return f"{self.emoji} {self.title}"


