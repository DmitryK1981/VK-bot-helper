ROLES_BY_ID: dict[str, Role] = {r.id: r for r in ROLES}
DEFAULT_ROLE_ID = "assistant"


def get_role(role_id: str) -> Role:
    """Возвращает роль; при неизвестном id — роль по умолчанию (устойчиво к старым данным)."""
    return ROLES_BY_ID.get(role_id, ROLES_BY_ID[DEFAULT_ROLE_ID])
